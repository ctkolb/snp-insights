"""Build external reference links for a finding.

Links are generated by code from the finding's own identifiers (rsID, gene,
condition, locus). The narrator never writes URLs, so no link can be
hallucinated. Preferring a link over model-written interpretation also keeps the
report out of the business of explaining what a variant "means".
"""
from urllib.parse import quote

GNOMAD_CHROMS = {str(i) for i in range(1, 23)} | {"X", "Y", "MT"}


def references_for(rsid, gene, condition, chromosome, position, ref, alt, assayability="snp"):
    refs = []
    if rsid:
        refs.append(("dbSNP", f"https://www.ncbi.nlm.nih.gov/snp/{rsid}"))
        refs.append(("ClinVar", f"https://www.ncbi.nlm.nih.gov/clinvar/?term={quote(rsid)}"))
        refs.append(("SNPedia", f"https://www.snpedia.com/index.php/{quote(rsid)}"))
        if (assayability == "snp" and chromosome in GNOMAD_CHROMS and position and ref and alt
                and len(ref) == 1 and len(alt) == 1 and ref in "ACGT" and alt in "ACGT"):
            refs.append(("gnomAD",
                         f"https://gnomad.broadinstitute.org/variant/{chromosome}-{position}-{ref}-{alt}?dataset=gnomad_r2_1"))
        refs.append(("OMIM", f"https://www.omim.org/search?search={quote(rsid)}"))
    if gene:
        refs.append(("MedlinePlus Genetics", f"https://medlineplus.gov/genetics/gene/{gene.lower()}/"))
    if condition:
        refs.append(("GeneReviews", f"https://www.ncbi.nlm.nih.gov/books/?term={quote(condition)}"))
    return [{"source": s, "url": u} for s, u in refs]
